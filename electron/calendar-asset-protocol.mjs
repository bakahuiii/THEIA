const ASSETS = new Map([
  ['calendar', { key: 'calendar', mediaType: 'image/jpeg' }],
  ['teaching-schedule', { key: 'teachingSchedule', mediaType: 'application/pdf' }],
  ['weekly-calendar', { key: 'weeklyCalendar', mediaType: 'application/pdf' }],
])

export const CALENDAR_ASSET_PROTOCOL = 'theia-calendar'
export const CALENDAR_ASSET_HOST = 'local'

function validPdfViewerHash(hash) {
  if (!hash) return true
  if (!/^#[a-zA-Z0-9=&._-]{1,256}$/.test(hash)) return false
  const params = new URLSearchParams(hash.slice(1))
  const seen = new Set()
  for (const [key, value] of params) {
    if (seen.has(key)) return false
    seen.add(key)
    if (key === 'page' && /^[1-9]\d*$/.test(value)) continue
    if (key === 'view' && value === 'FitH') continue
    if ((key === 'toolbar' || key === 'navpanes') && /^[01]$/.test(value)) continue
    return false
  }
  return seen.size > 0
}

export function calendarAssetUrl(key) {
  const entry = [...ASSETS.entries()].find(([, value]) => value.key === key)
  if (!entry) throw new Error('Unknown academic calendar asset')
  return `${CALENDAR_ASSET_PROTOCOL}://${CALENDAR_ASSET_HOST}/${entry[0]}`
}

export function parseCalendarAssetUrl(rawUrl) {
  const raw = String(rawUrl || '')
  let decodedRaw
  try {
    decodedRaw = decodeURIComponent(raw)
  } catch {
    return null
  }
  if (/(?:^|[\\/])\.{1,2}(?:[\\/?#]|$)/.test(decodedRaw)) return null
  let url
  try {
    url = new URL(raw)
  } catch {
    return null
  }
  if (url.protocol !== `${CALENDAR_ASSET_PROTOCOL}:` || url.hostname !== CALENDAR_ASSET_HOST) return null
  // PDF viewer state lives in the fragment and never selects a local file.
  // Queries remain forbidden, and only the parameters generated by THEIA pass.
  if (url.username || url.password || url.port || url.search) return null
  const rawPath = url.pathname
  if (!/^\/[a-z-]+$/.test(rawPath)) return null
  const asset = ASSETS.get(rawPath.slice(1))
  if (!asset || (url.hash && (asset.mediaType !== 'application/pdf' || !validPdfViewerHash(url.hash)))) return null
  return { ...asset }
}
